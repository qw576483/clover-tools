// 客户端（c#）输出配置。
//
// 目录结构：
//
//	CodeDir/         <- 上层 namespace Table（业务扩展层，可编辑）
//	  <Logical>.cs
//	  Registry.cs
//	CodeDir/Base/    <- base namespace Table.Base（覆盖）
//	  BaseTable.cs
//	  Base<Logical>.cs
//	  BaseRegistry.cs
//
// tsv 数据单文件输出到 TSVDir/<Logical>.tsv（每次覆盖）。
type CSOutput struct {
	CodeDir     string // 代码目录（code/）
	BaseCodeDir string // base 代码目录（code/base）
	TSVDir      string // tsv 数据目录（直接输出 <logical>.tsv，每次覆盖）
}

// 返回列的 C# 类型。
func CsType(t def.ColumnType) string {
	switch t {
	case def.TypeInt, def.TypeInt32:
		return "int"
	case def.TypeInt64:
		return "long"
	case def.TypeFloat32, def.TypeFloat64:
		return "float"
	case def.TypeString:
		return "string"
	case def.TypeMapIntInt:
		return "Dictionary<int, int>"
	case def.TypeMapIntString:
		return "Dictionary<int, string>"
	case def.TypeSliceInt:
		return "int[]"
	case def.TypeSliceString:
		return "string[]"
	case def.TypeVector3:
		return "Vector3"
	default:
		return "string"
	}
}

// 生成客户端（c#）全部文件。仅处理含客户端侧列的表。
func CsGenerate(out CSOutput, tables []*def.TableDef, overwriteNonBase bool) ([]MappingEntry, error) {
	if out.BaseCodeDir == "" {
		out.BaseCodeDir = filepath.Join(out.CodeDir, "Base")
	}
	var entries []MappingEntry
	var metas []csTableMeta

	rtPath := filepath.Join(out.BaseCodeDir, "BaseTable.cs")
	if _, err := WriteFile(rtPath, csRuntime(), true); err != nil {
		return nil, fmt.Errorf("gen: 写 c# 运行时失败: %w", err)
	}
	entries = append(entries, MappingEntry{AbsPath: rtPath, Source: "-", Sheet: "-", Side: "c", Base: true, Kind: "cs"})

	for _, t := range tables {
		logical, _, ok := ParseTableName(t.Name)
		if !ok {
			logical = t.Name
		}
		cols := t.ColumnsForSide(def.SideClient)
		if len(cols) == 0 {
			continue
		}
		meta := csTableMeta{
			Name:       logical,
			Tsv:        ToGoIdent(logical) + ".tsv",
			BaseRow:    "Base" + ToGoIdent(logical) + "Row",
			BaseTable:  "Base" + ToGoIdent(logical) + "Table",
			UpperTable: ToGoIdent(logical) + "Table",
			PkCsType:   csPkType(t),
		}
		metas = append(metas, meta)

		baseCode := csBaseTable(t, cols, meta)
		basePath := filepath.Join(out.BaseCodeDir, "Base"+ToGoIdent(logical)+".cs")
		if _, err := WriteFile(basePath, baseCode, true); err != nil {
			return nil, fmt.Errorf("gen: 写 c# base 失败: %w", err)
		}
		entries = append(entries, MappingEntry{AbsPath: basePath, Source: t.SourceFile, Sheet: t.Name, Side: "c", Base: true, Kind: "cs"})

		if err := WriteTSV(out.TSVDir, meta.Tsv, t, def.SideClient); err != nil {
			return nil, fmt.Errorf("gen: 写客户端 tsv 失败: %w", err)
		}
		entries = append(entries,
			MappingEntry{AbsPath: filepath.Join(out.TSVDir, meta.Tsv), Source: t.SourceFile, Sheet: t.Name, Side: "c", Base: false, Kind: "tsv"},
		)

		upperCode := csUpperTable(meta)
		upperPath := filepath.Join(out.CodeDir, ToGoIdent(logical)+".cs")
		if _, err := WriteFile(upperPath, upperCode, false); err != nil {
			return nil, fmt.Errorf("gen: 写 c# 上层失败: %w", err)
		}
		entries = append(entries, MappingEntry{AbsPath: upperPath, Source: t.SourceFile, Sheet: t.Name, Side: "c", Base: false, Kind: "cs"})
	}

	baseReg := csBaseRegistry(metas)
	baseRegPath := filepath.Join(out.BaseCodeDir, "BaseRegistry.cs")
	if _, err := WriteFile(baseRegPath, baseReg, true); err != nil {
		return nil, fmt.Errorf("gen: 写 c# base registry 失败: %w", err)
	}
	entries = append(entries, MappingEntry{AbsPath: baseRegPath, Source: "-", Sheet: "-", Side: "c", Base: true, Kind: "cs"})

	upperReg := csUpperRegistry(metas)
	upperRegPath := filepath.Join(out.CodeDir, "Registry.cs")
	if _, err := WriteFile(upperRegPath, upperReg, true); err != nil {
		return nil, fmt.Errorf("gen: 写 c# 上层 registry 失败: %w", err)
	}
	entries = append(entries, MappingEntry{AbsPath: upperRegPath, Source: "-", Sheet: "-", Side: "c", Base: false, Kind: "cs"})

	return entries, nil
}

type csTableMeta struct {
	Name       string
	Tsv        string
	BaseRow    string
	BaseTable  string
	UpperTable string
	PkCsType   string
}

func csPkType(t *def.TableDef) string {
	if t.PkIsString {
		return "string"
	}
	return "int"
}

func csRuntime() string {
	return `// Code generated by core. DO NOT EDIT (base runtime, regenerated each run).
using System;
using System.Collections.Generic;

namespace Table
{
    // Vector3 三维向量（策划用 ';' 或 ',' 分隔的三个浮点数）。
    public struct Vector3
    {
        public float X, Y, Z;
    }

    public static class TableParsers
    {
        public static string Cell(string[] rec, int i)
        {
            if (i < 0 || i >= rec.Length) return "";
            return rec[i];
        }

        public static int ToInt(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return 0;
            return int.TryParse(s.Trim(), out var v) ? v : 0;
        }

        public static long ToLong(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return 0L;
            return long.TryParse(s.Trim(), out var v) ? v : 0L;
        }

        public static float ToFloat(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return 0f;
            return float.TryParse(s.Trim(), out var v) ? v : 0f;
        }

        public static Dictionary<int, int> ParseMapIntInt(string s)
        {
            var res = new Dictionary<int, int>();
            if (string.IsNullOrWhiteSpace(s)) return res;
            foreach (var pair in s.Split('|'))
            {
                var p = pair.Trim();
                if (p == "") continue;
                var kv = p.Split(new[] { ';' }, 2);
                if (kv.Length != 2) kv = p.Split(new[] { ':' }, 2);
                if (kv.Length != 2) continue;
                res[ToInt(kv[0])] = ToInt(kv[1]);
            }
            return res;
        }

        public static Dictionary<int, string> ParseMapIntString(string s)
        {
            var res = new Dictionary<int, string>();
            if (string.IsNullOrWhiteSpace(s)) return res;
            foreach (var pair in s.Split('|'))
            {
                var p = pair.Trim();
                if (p == "") continue;
                var kv = p.Split(new[] { ';' }, 2);
                if (kv.Length != 2) kv = p.Split(new[] { ':' }, 2);
                if (kv.Length != 2) continue;
                res[ToInt(kv[0])] = kv[1].Trim();
            }
            return res;
        }

        public static int[] ParseSliceInt(string s)
        {
            var res = new List<int>();
            if (string.IsNullOrWhiteSpace(s)) return res.ToArray();
            foreach (var e in s.Split(';'))
            {
                var x = e.Trim();
                if (x == "") continue;
                res.Add(ToInt(x));
            }
            return res.ToArray();
        }

        public static string[] ParseSliceString(string s)
        {
            var res = new List<string>();
            if (string.IsNullOrWhiteSpace(s)) return res.ToArray();
            foreach (var e in s.Split(';')) res.Add(e.Trim());
            return res.ToArray();
        }

        public static Vector3 ParseVector3(string s)
        {
            var v = new Vector3();
            if (string.IsNullOrWhiteSpace(s)) return v;
            var sep = s.IndexOf(';') >= 0 ? ';' : ',';
            var parts = s.Split(sep);
            if (parts.Length > 0) v.X = ToFloat(parts[0]);
            if (parts.Length > 1) v.Y = ToFloat(parts[1]);
            if (parts.Length > 2) v.Z = ToFloat(parts[2]);
            return v;
        }
    }
}
`
}

func csBaseTable(t *def.TableDef, cols []def.Column, m csTableMeta) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by core. DO NOT EDIT (base, regenerated each run).\n")
	fmt.Fprintf(&b, "using System;\nusing System.Collections.Generic;\nusing System.IO;\n\n")
	fmt.Fprintf(&b, "namespace Table\n{\n")

	fmt.Fprintf(&b, "\t// %s 表 %q 的一行（强类型）。\n", m.BaseRow, t.Name)
	fmt.Fprintf(&b, "\tpublic class %s\n\t{\n", m.BaseRow)
	for _, c := range cols {
		comment := strings.TrimSpace(c.Comment)
		if comment != "" {
			fmt.Fprintf(&b, "\t\tpublic %s %s; // %s\n", CsType(c.Type), ToGoIdent(c.Name), comment)
		} else {
			fmt.Fprintf(&b, "\t\tpublic %s %s;\n", CsType(c.Type), ToGoIdent(c.Name))
		}
	}
	fmt.Fprintf(&b, "\t}\n\n")

	fmt.Fprintf(&b, "\t// %s 表 %q 的只读容器（按主键索引）。\n", m.BaseTable, t.Name)
	fmt.Fprintf(&b, "\tpublic class %s\n\t{\n", m.BaseTable)
	fmt.Fprintf(&b, "\t\tprivate List<%s> rows = new List<%s>();\n", m.BaseRow, m.BaseRow)
	fmt.Fprintf(&b, "\t\tprivate Dictionary<%s, %s> index = new Dictionary<%s, %s>();\n\n", m.PkCsType, m.BaseRow, m.PkCsType, m.BaseRow)
	fmt.Fprintf(&b, "\t\tpublic %s Get(%s id) => index.ContainsKey(id) ? index[id] : null;\n", m.BaseRow, m.PkCsType)
	fmt.Fprintf(&b, "\t\tpublic int Count => rows.Count;\n")
	fmt.Fprintf(&b, "\t\tpublic List<%s> All() => rows;\n\n", m.BaseRow)
	fmt.Fprintf(&b, "\t\t// Load 从 tsv 加载（首行为列名表头，'\\t' 分隔）。整体替换旧数据。\n")
	fmt.Fprintf(&b, "\t\tpublic void Load(string path)\n\t\t{\n")
	fmt.Fprintf(&b, "\t\t\tvar lines = File.ReadAllLines(path);\n")
	fmt.Fprintf(&b, "\t\t\tif (lines.Length < 1) return;\n")
	fmt.Fprintf(&b, "\t\t\trows = new List<%s>();\n", m.BaseRow)
	fmt.Fprintf(&b, "\t\t\tindex = new Dictionary<%s, %s>();\n", m.PkCsType, m.BaseRow)
	fmt.Fprintf(&b, "\t\t\tfor (int li = 1; li < lines.Length; li++)\n\t\t\t{\n")
	fmt.Fprintf(&b, "\t\t\t\tif (string.IsNullOrEmpty(lines[li])) continue;\n")
	fmt.Fprintf(&b, "\t\t\t\tvar rec = lines[li].Split('\\t');\n")
	fmt.Fprintf(&b, "\t\t\t\tvar row = new %s();\n", m.BaseRow)
	for i, c := range cols {
		fld := ToGoIdent(c.Name)
		switch c.Type {
		case def.TypeInt, def.TypeInt32:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ToInt(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeInt64:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ToLong(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeFloat32, def.TypeFloat64:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ToFloat(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeString:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.Cell(rec, %d);\n", fld, i)
		case def.TypeMapIntInt:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ParseMapIntInt(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeMapIntString:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ParseMapIntString(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeSliceInt:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ParseSliceInt(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeSliceString:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ParseSliceString(TableParsers.Cell(rec, %d));\n", fld, i)
		case def.TypeVector3:
			fmt.Fprintf(&b, "\t\t\t\trow.%s = TableParsers.ParseVector3(TableParsers.Cell(rec, %d));\n", fld, i)
		}
	}
	fmt.Fprintf(&b, "\t\t\t\trows.Add(row);\n")
	fmt.Fprintf(&b, "\t\t\t\tindex[row.%s] = row;\n", ToGoIdent(cols[0].Name))
	fmt.Fprintf(&b, "\t\t\t}\n")
	fmt.Fprintf(&b, "\t\t}\n")
	fmt.Fprintf(&b, "\t}\n}\n")
	return b.String()
}

func csUpperTable(m csTableMeta) string {
	return fmt.Sprintf(`// Code generated by core. EDITABLE (上层，首次生成后不再覆盖)。
// 业务可在此安全追加逻辑、覆写下方三个加载钩子。
using System;

namespace Table
{
    public class %[1]s : %[2]s
    {
        public virtual void OnBeforeLoad() { }
        public virtual void OnLoadRow(%[3]s row) { }
        public virtual void OnAfterLoad() { }

        // LoadWithHooks 加载 tsv 并在加载前/中/后触发钩子。
        public void LoadWithHooks(string path)
        {
            OnBeforeLoad();
            base.Load(path);
            foreach (var row in All()) OnLoadRow(row);
            OnAfterLoad();
        }
    }
}
`, m.UpperTable, m.BaseTable, m.BaseRow)
}

func csBaseRegistry(metas []csTableMeta) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by core. DO NOT EDIT (base registry, regenerated each run).\n")
	fmt.Fprintf(&b, "using System.IO;\n\nnamespace Table\n{\n")
	fmt.Fprintf(&b, "\tpublic class BaseTables\n\t{\n")
	for _, m := range metas {
		fmt.Fprintf(&b, "\t\tpublic %s %s = new %s();\n", m.BaseTable, ToGoIdent(m.Name), m.BaseTable)
	}
	fmt.Fprintf(&b, "\n\t\t// LoadAll 从 dir 加载全部 base 表（dir/<name>.tsv）。\n")
	fmt.Fprintf(&b, "\t\tpublic void LoadAll(string dir)\n\t\t{\n")
	for _, m := range metas {
		fmt.Fprintf(&b, "\t\t\t%s.Load(Path.Combine(dir, %q));\n", ToGoIdent(m.Name), m.Tsv)
	}
	fmt.Fprintf(&b, "\t\t}\n\t}\n}\n")
	return b.String()
}

func csUpperRegistry(metas []csTableMeta) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by core. DO NOT EDIT (上层 registry，每次运行重新生成)。\n")
	fmt.Fprintf(&b, "using System.IO;\n\nnamespace Table\n{\n")
	fmt.Fprintf(&b, "\tpublic class Tables\n\t{\n")
	fmt.Fprintf(&b, "\t\t// Default 全局配置表单例。引擎加载后即为已加载实例，业务直接 Tables.Default.<表名>.Get(id)。\n")
	fmt.Fprintf(&b, "\t\tpublic static Tables Default = new Tables();\n")
	for _, m := range metas {
		fmt.Fprintf(&b, "\t\tpublic %s %s = new %s();\n", m.UpperTable, ToGoIdent(m.Name), m.UpperTable)
	}
	fmt.Fprintf(&b, "\n\t\t// LoadAll 从 dir 加载全部业务表（dir/<name>.tsv），并触发各表钩子。\n")
	fmt.Fprintf(&b, "\t\tpublic void LoadAll(string dir)\n\t\t{\n")
	for _, m := range metas {
		fmt.Fprintf(&b, "\t\t\t%s.LoadWithHooks(Path.Combine(dir, %q));\n", ToGoIdent(m.Name), m.Tsv)
	}
	fmt.Fprintf(&b, "\t\t}\n\t}\n}\n")
	return b.String()
}
